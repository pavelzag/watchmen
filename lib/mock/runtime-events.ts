export function getDemoRuntimeRequestEvents(rules: RuntimeSecurityRule[]): RuntimeRequestEvent[] {
  const effectiveRules = rules.length > 0 ? rules : DEMO_RUNTIME_RULES;
  const now = Date.now();
  return DEMO_REQUEST_SEEDS.map((seed) =>
    applyRuntimeDecision(
      {
        id: seed.id,
        ts: new Date(now - seed.ageMs).toISOString(),
        sourceIp: seed.sourceIp,
        sourcePort: seed.sourcePort,
        sourceGeo: seed.sourceGeo,
        method: seed.method,
        path: seed.path,
        contentType: seed.contentType,
        bodySize: seed.bodySize,
        bodySample: seed.bodySample,
        statusCode: seed.statusCode,
        destinationService: seed.destinationService,
        destinationNamespace: seed.destinationNamespace,
        destinationPod: seed.destinationPod,
        destinationWorkload: seed.destinationWorkload,
      },
      effectiveRules,
    )
  );
}

